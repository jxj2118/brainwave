type IconifyIcon = { body: string };
const data = solar as {
  icons: Record<string, IconifyIcon>;
  aliases?: Record<string, { parent: string }>;
};
function body(name: string): string {
  let key = name;
  for (let depth = 0; depth < 4; depth++) {
    const icon = data.icons[key];
    if (icon) return icon.body;
    const alias = data.aliases?.[key];
    if (!alias) break;
    key = alias.parent;
  }
  throw new Error(`Solar icon not found: ${name}`);
}

const lines = Object.entries(icons).map(
  ([name, solarName]) =>
    `  ${name}: {\n    linear: ${JSON.stringify(body(`${solarName}-linear`))},\n    bold: ${JSON.stringify(body(`${solarName}-bold`))},\n  },`,
);
const target = resolve("src/shared/solarIcons.ts");
writeFileSync(
  target,
  `// Generated by scripts/generate-icons.ts from @iconify-json/solar (CC BY 4.0, 480 Design). Do not edit.\nexport const solarIcons = {\n${lines.join("\n")}\n} as const;\n`,
);
await $`bunx prettier --write ${target}`.quiet();
